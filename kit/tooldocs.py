"""Tool docs: one page per tool under docs/tools/, written to docs/TOOL-DOCS.md and checked against the code.

  python -m kit.tooldocs check [--page ID]   every page, the index and coverage; exit 1 on any problem (a unit test
                                             runs this); --page checks one page only, quickly, while you write it
  python -m kit.tooldocs index               rewrite the generated table in docs/tools/README.md and docs/tools/index.json
  python -m kit.tooldocs list [--json]       every tool: id, status, kind, how to run it, one-line summary
  python -m kit.tooldocs show ID             print one tool's page (close matches when ID is unknown; exit 2)
  python -m kit.tooldocs new ID [--kind K] [--status S]   start docs/tools/ID.md from templates/tool-doc.md
                                             (templates/tool-doc-branch.md for --status "Branch only")

What check enforces (docs/TOOL-DOCS.md explains why):

- each page has a title, a one-sentence summary, the "At a glance" table with every field in order, and every required
  section in order (the Branch only status has its own shorter list);
- Status and Kind use the standard's words, Checked starts with a date, Retired names what replaced it and Branch
  only names the branch;
- every path in Code and Tests exists (Branch only pages excepted, since their code is elsewhere);
- every `python -m kit COMMAND [ACTION]` in Run is a real command, and every long option of it (and of each of its
  actions) appears on the page in code;
- every kit module and package, every entry directly under scripts/ and every kit command and action is named by
  some page (Code for files, Run for commands), so a new tool cannot land without a page;
- the generated index matches the pages.

Standard library only. The Scrolls and Scrolls-private repositories carry identical copies of this module.
"""

import argparse
import difflib
import json
import re
import subprocess
import sys
from datetime import date
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PAGES = ROOT / "docs" / "tools"
INDEX_MD = PAGES / "README.md"
INDEX_JSON = PAGES / "index.json"
TEMPLATE = ROOT / "templates" / "tool-doc.md"
STANDARD = "docs/TOOL-DOCS.md"

FIELDS = ("Id", "Status", "Kind", "Run", "Code", "Tests", "Needs", "Runs on", "Network", "Writes", "Go-ahead",
          "Released", "Checked")
OPTIONAL_FIELDS = ("Guide", "Replaced by", "Branch")
STATUSES = ("Current", "Experimental", "Retired", "Branch only")
KINDS = ("kit command", "kit module", "python module", "script", "script folder", "agent tool", "app", "model",
         "package", "skill", "patch", "workflow", "data")
SECTIONS = ("What it does", "When to use it", "Quick start", "Commands and options", "Inputs", "Outputs",
            "How it works", "Checks and controls", "Failure modes", "Cost and time", "For agents", "Tests",
            "History", "Related")
# A library has a Python API where a command has options; a page may have both.
ALTERNATIVES = {"Commands and options": ("Commands and options", "Python API")}
BRANCH_SECTIONS = ("What it does", "Where the code is", "How to run it", "Inputs and outputs",
                   "Why it is not on the default branch", "For agents", "History", "Related")
ID_RE = re.compile(r"[a-z0-9][a-z0-9-]*")
DATE_RE = re.compile(r"\d{4}-\d{2}-\d{2}\b")
SUMMARY_MAX = 300
LEFTOVER = "<!-- Write:"
START = "<!-- tooldocs:start (generated by python -m kit.tooldocs index; do not edit by hand) -->"
END = "<!-- tooldocs:end -->"
KIT_RUN = re.compile(r"^python3? -m kit ([a-z0-9][a-z0-9-]*)(?: ([a-z0-9][a-z0-9-]*))?")
PATHLIKE = re.compile(r"^[A-Za-z0-9_.][A-Za-z0-9_./*-]*$")
FENCE = re.compile(r"^(```|~~~).*?^\1[ \t]*$", re.S | re.M)
SPAN = re.compile(r"`([^`\n]+)`")

INTRO = """# Tool pages

One page per tool, current, retired or only on another branch, written to the standard in
[`../TOOL-DOCS.md`](../TOOL-DOCS.md) and checked against the code by `python -m kit.tooldocs check`, which the tests
run. Each page answers the same questions in the same order, so a person can read it and an agent can find its way
in it: what the tool does, when to use it, a quick start, every option, inputs, outputs, how it works, the controls
that let its result fail, failure modes, cost and time, rules for agents, tests, history and related tools.

For agents: `python -m kit.tooldocs list --json` lists every tool with its status, kind, entry point and summary, and
`python -m kit.tooldocs show ID` prints one page. [`index.json`](index.json) holds the same list.

The table below is generated from the pages by `python -m kit.tooldocs index`; edit the pages, never the table.
"""


class Page:
    """One parsed tool page."""

    def __init__(self, path, text):
        self.path = path
        self.text = text
        self.problems = []
        self.title = ""
        self.summary = ""
        self.fields = {}
        self.order = []
        self.sections = []
        self._parse()

    @property
    def id(self):
        return self.path.stem

    def field(self, name):
        return self.fields.get(name, "")

    def spans(self, name):
        return SPAN.findall(self.field(name))

    def _parse(self):
        body = FENCE.sub("", self.text)
        lines = body.splitlines()
        if not lines or not lines[0].startswith("# "):
            self.problems.append("the first line is not a '# Title' heading")
        else:
            self.title = lines[0][2:].strip()
        # The summary: the first paragraph after the title, before the table.
        para, i = [], 1
        while i < len(lines) and not lines[i].strip():
            i += 1
        while i < len(lines) and lines[i].strip() and not lines[i].lstrip().startswith(("|", "#")):
            para.append(lines[i].strip())
            i += 1
        self.summary = " ".join(para)
        # The "At a glance" table: the first table on the page.
        while i < len(lines) and not lines[i].lstrip().startswith("|"):
            if lines[i].startswith("## "):
                break
            i += 1
        rows = []
        while i < len(lines) and lines[i].lstrip().startswith("|"):
            rows.append(lines[i].strip())
            i += 1
        if len(rows) < 2 or [c.strip() for c in rows[0].strip("|").split("|")] != ["Field", "Value"]:
            self.problems.append("no 'At a glance' table with the header | Field | Value | after the summary")
        else:
            for row in rows[2:]:
                cells = row.strip().strip("|").split("|")
                if len(cells) != 2:
                    self.problems.append(f"table row {row[:60]!r} does not have exactly two cells (no '|' in values)")
                    continue
                name, value = cells[0].strip(), cells[1].strip()
                if name in self.fields:
                    self.problems.append(f"field {name!r} appears twice")
                self.fields[name] = value
                self.order.append(name)
        # Sections and their bodies (to catch empty ones), from the full text: a heading inside a fenced
        # block is not a heading, but the block is content of its section.
        self.bodies = {}
        current, fence = None, None
        for line in self.text.splitlines():
            marker = re.match(r"^(```|~~~)", line)
            if fence is None and line.startswith("## "):
                current = line[3:].strip()
                self.sections.append(current)
                self.bodies[current] = []
                continue
            if marker:
                fence = None if fence == marker.group(1) else (fence or marker.group(1))
            if current is not None:
                self.bodies[current].append(line)

    def code_text(self):
        """Everything inside code spans and fenced blocks: where options and commands must appear."""
        blocks = [m.group(0) for m in FENCE.finditer(self.text)]
        return "\n".join(blocks + SPAN.findall(FENCE.sub("", self.text)))


def _required_sections(page):
    return BRANCH_SECTIONS if page.field("Status") == "Branch only" else SECTIONS


def check_page(page, root=ROOT, commands=None):
    """Problems with one page, each a short sentence. commands: {command: {action or None: [options]}}."""
    problems = list(page.problems)
    if not ID_RE.fullmatch(page.id):
        problems.append(f"file name {page.path.name!r}: an id is lowercase letters, digits and hyphens")
    if not page.summary:
        problems.append("no one-sentence summary between the title and the table")
    elif len(page.summary) > SUMMARY_MAX:
        problems.append(f"the summary is {len(page.summary)} characters; keep it to {SUMMARY_MAX} (one sentence)")
    if page.fields:
        unknown = [f for f in page.order if f not in FIELDS + OPTIONAL_FIELDS]
        if unknown:
            problems.append(f"unknown fields {unknown}; allowed: {list(FIELDS + OPTIONAL_FIELDS)}")
        missing = [f for f in FIELDS if f not in page.fields]
        if missing:
            problems.append(f"missing fields {missing}")
        present = [f for f in page.order if f in FIELDS]
        if not missing and present != list(FIELDS):
            problems.append(f"fields out of order; the order is {list(FIELDS)}")
        empty = [f for f in page.order if not page.fields.get(f)]
        if empty:
            problems.append(f"empty fields {empty}; write 'None' and why when there is nothing")
        idv = page.spans("Id")
        if "Id" in page.fields and idv != [page.id]:
            problems.append(f"Id is {page.field('Id')!r}; write `{page.id}`, the file name without .md")
        status = page.field("Status")
        if status and status not in STATUSES:
            problems.append(f"Status {status!r} is not one of {list(STATUSES)}")
        for kind in [k.strip() for k in page.field("Kind").split(",") if k.strip()]:
            if kind not in KINDS:
                problems.append(f"Kind {kind!r} is not one of {list(KINDS)}")
        if page.field("Checked") and not DATE_RE.match(page.field("Checked")):
            problems.append("Checked must start with the date, YYYY-MM-DD")
        if status == "Retired" and not page.field("Replaced by"):
            problems.append("a Retired tool needs the field 'Replaced by' (write 'Nothing' if nothing replaced it)")
        if status == "Branch only" and not page.field("Branch"):
            problems.append("a Branch only tool needs the field 'Branch': the branch and commit that hold its code")
        if status != "Branch only":
            for name in ("Code", "Tests"):
                for span in page.spans(name):
                    if PATHLIKE.match(span) and ("/" in span or "." in span) and not _exists(root, span):
                        problems.append(f"{name} names {span!r}, which is not in the repository")
            if commands is not None:
                problems.extend(_check_runs(page, commands))
    if LEFTOVER in page.text:
        problems.append(f"template guidance ({LEFTOVER} ...) is still on the page; replace it with the text")
    problems.extend(_check_sections(page))
    return problems


def _exists(root, rel):
    if any(c in rel for c in "*?["):
        return any(root.glob(rel))
    return (root / rel.rstrip("/")).exists()


def _check_sections(page):
    problems = []
    want = _required_sections(page)
    have = page.sections
    pos = -1
    for name in want:
        names = ALTERNATIVES.get(name, (name,)) if want is SECTIONS else (name,)
        found = [have.index(n) for n in names if n in have]
        if not found:
            problems.append(f"missing section '## {' or ## '.join(names)}'")
            continue
        first = min(found)
        if first < pos:
            problems.append(f"section '## {have[first]}' is out of order; the order is in {STANDARD}")
        pos = max(pos, first)
        for n in names:
            if n in page.bodies and not "".join(page.bodies[n]).strip():
                problems.append(f"section '## {n}' is empty")
    return problems


def _check_runs(page, commands):
    problems = []
    code = page.code_text()
    for span in page.spans("Run"):
        m = KIT_RUN.match(span)
        if not m:
            continue
        command, action = m.group(1), m.group(2)
        if command not in commands:
            problems.append(f"Run names `python -m kit {command}`, which is not a kit command")
            continue
        actions = commands[command]
        if action and action not in actions and None in actions and len(actions) == 1:
            action = None          # a positional argument, such as `python -m kit plan SCROLL`
        if action and action not in actions:
            problems.append(f"Run names `python -m kit {command} {action}`, which is not an action of {command}")
            continue
        wanted = [None] + ([action] if action else [a for a in actions if a is not None])
        for a in wanted:
            for opt in actions.get(a, []):
                if not re.search(r"(?<![\w-])" + re.escape(opt) + r"(?![\w-])", code):
                    where = f"{command} {a}" if a else command
                    problems.append(f"option `{opt}` of `python -m kit {where}` is not on the page in code")
            if a is not None and not re.search(r"(?<![\w-])" + re.escape(a) + r"(?![\w-])", code):
                problems.append(f"action `{a}` of `python -m kit {command}` is not on the page in code")
    return problems


def kit_commands():
    """{command: {None: [its own long options], action: [that action's long options], ...}} from kit's parser."""
    from . import cli
    build = getattr(cli, "build_parser", None) or getattr(cli, "_parser")
    parser = build()
    subs = next(a for a in parser._actions if isinstance(a, argparse._SubParsersAction))
    out = {}
    for name, sub in subs.choices.items():
        entry = {None: _long_options(sub)}
        for act in sub._actions:
            if isinstance(act, argparse._SubParsersAction):
                for aname, asub in act.choices.items():
                    entry[aname] = _long_options(asub)
        out[name] = entry
    return out


def _long_options(parser):
    opts = []
    for act in parser._actions:
        for s in act.option_strings:
            if s.startswith("--") and s != "--help" and s not in opts:
                opts.append(s)
    return opts


def tracked(root=ROOT):
    try:
        out = subprocess.run(["git", "ls-files"], cwd=root, capture_output=True, text=True, check=True).stdout
        return [f for f in out.split("\n") if f]
    except (OSError, subprocess.CalledProcessError):
        return [p.relative_to(root).as_posix() for p in root.rglob("*") if p.is_file() and ".git" not in p.parts]


def coverage(pages, files, commands):
    """Problems: kit modules, scripts entries, commands and actions that no page names."""
    named = set()
    runs = set()
    for page in pages:
        for span in page.spans("Code"):
            named.add(span.rstrip("/"))
        for span in page.spans("Run"):
            m = KIT_RUN.match(span)
            if m:
                runs.add((m.group(1), m.group(2)))
    def covered(target):
        return any(n == target or n.startswith(target + "/") or target.startswith(n + "/") for n in named)
    problems = []
    wanted = set()
    for f in files:
        parts = f.split("/")
        if len(parts) == 2 and parts[0] == "kit" and f.endswith(".py") and parts[1] not in ("__init__.py", "__main__.py"):
            wanted.add(f)
        elif len(parts) >= 3 and parts[0] == "kit" and parts[1] != "data" and parts[2] == "__init__.py":
            wanted.add(f"kit/{parts[1]}")
        elif len(parts) >= 2 and parts[0] == "scripts":
            wanted.add(f"scripts/{parts[1]}")
    for target in sorted(wanted):
        if not covered(target):
            stem = Path(target).stem.replace("_", "-").lower()
            problems.append(f"{target} has no tool page: start one with `python -m kit.tooldocs new {stem}` "
                            f"and name `{target}` in its Code field ({STANDARD})")
    for command, actions in sorted(commands.items()):
        if (command, None) in runs:
            continue
        missing = [a for a in actions if a is not None and (command, a) not in runs]
        if len(actions) == 1 or missing:
            what = [f"{command} {a}" for a in missing] or [command]
            for w in what:
                problems.append(f"`python -m kit {w}` is on no tool page's Run field ({STANDARD})")
    return problems


def load_pages(pages_dir=PAGES):
    out = []
    for path in sorted(pages_dir.glob("*.md")):
        if path.name == "README.md":
            continue
        out.append(Page(path, path.read_text(encoding="utf-8")))
    return out


def entry(page, root=ROOT):
    return {
        "id": page.id,
        "title": page.title,
        "summary": page.summary,
        "status": page.field("Status"),
        "kind": [k.strip() for k in page.field("Kind").split(",") if k.strip()],
        "run": page.spans("Run") or [page.field("Run")],
        "code": page.spans("Code"),
        "tests": page.spans("Tests"),
        "released": page.field("Released"),
        "go_ahead": page.field("Go-ahead"),
        "checked": page.field("Checked"),
        "guide": page.field("Guide"),
        "page": page.path.relative_to(root).as_posix(),
        "sections": page.sections,
    }


def render_json(pages, root=ROOT):
    data = {"about": ("Every tool's page in docs/tools/, generated by python -m kit.tooldocs index from the pages; "
                      "edit the pages, not this file. The standard is " + STANDARD + "."),
            "tools": [entry(p, root) for p in sorted(pages, key=lambda p: p.id)]}
    return json.dumps(data, indent=1, ensure_ascii=False) + "\n"


def render_table(pages):
    rank = {s: i for i, s in enumerate(STATUSES)}
    rows = ["| Tool | Status | Kind | Run | What it does |", "| --- | --- | --- | --- | --- |"]
    for p in sorted(pages, key=lambda p: (rank.get(p.field("Status"), len(STATUSES)), p.id)):
        run = p.spans("Run")
        run_cell = f"`{run[0]}`" if run else p.field("Run")
        title = p.title.replace("|", "/")
        summary = p.summary.replace("|", "/")
        rows.append(f"| [{title}]({p.path.name}) | {p.field('Status')} | {p.field('Kind')} | {run_cell} | {summary} |")
    return "\n".join(rows)


def render_index(pages, current=None):
    block = f"{START}\n\n{render_table(pages)}\n\n{END}"
    if current and START in current and END in current:
        head, rest = current.split(START, 1)
        tail = rest.split(END, 1)[1]
        return head + block + tail
    return INTRO + "\n" + block + "\n"


def check_all(root=ROOT, page_id=None):
    pages_dir = root / "docs" / "tools"
    pages = load_pages(pages_dir)
    try:
        commands = kit_commands() if root == ROOT else None
    except Exception as exc:  # a broken parser is itself a problem to report, not a crash
        return [f"cannot build kit's parser: {exc}"]
    if page_id is not None:
        page = next((p for p in pages if p.id == page_id), None)
        if page is None:
            return [f"no page docs/tools/{page_id}.md"]
        return [f"{page.path.relative_to(root).as_posix()}: {m}" for m in check_page(page, root, commands)]
    problems = []
    for page in pages:
        problems += [f"{page.path.relative_to(root).as_posix()}: {m}" for m in check_page(page, root, commands)]
    if commands is not None:
        problems += coverage(pages, tracked(root), commands)
    index_md = pages_dir / "README.md"
    current = index_md.read_text(encoding="utf-8") if index_md.exists() else None
    if current != render_index(pages, current):
        problems.append("docs/tools/README.md is out of date: run python -m kit.tooldocs index")
    index_json = pages_dir / "index.json"
    if not index_json.exists() or index_json.read_text(encoding="utf-8") != render_json(pages, root):
        problems.append("docs/tools/index.json is out of date: run python -m kit.tooldocs index")
    return problems


def write_index(root=ROOT):
    pages_dir = root / "docs" / "tools"
    pages = load_pages(pages_dir)
    index_md = pages_dir / "README.md"
    current = index_md.read_text(encoding="utf-8") if index_md.exists() else None
    index_md.write_text(render_index(pages, current), encoding="utf-8")
    (pages_dir / "index.json").write_text(render_json(pages, root), encoding="utf-8")
    return len(pages)


def new_page(page_id, kind="kit command", status="Current", root=ROOT, today=None):
    if not ID_RE.fullmatch(page_id):
        raise ValueError(f"{page_id!r}: an id is lowercase letters, digits and hyphens")
    if status not in STATUSES:
        raise ValueError(f"status {status!r} is not one of {list(STATUSES)}")
    path = root / "docs" / "tools" / f"{page_id}.md"
    if path.exists():
        raise ValueError(f"{path.relative_to(root).as_posix()} already exists")
    template = "tool-doc-branch.md" if status == "Branch only" else "tool-doc.md"
    text = (root / "templates" / template).read_text(encoding="utf-8")
    text = (text.replace("{id}", page_id).replace("{kind}", kind).replace("{status}", status)
            .replace("{date}", (today or date.today()).isoformat()))
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")
    return path


def main(argv=None):
    parser = argparse.ArgumentParser(prog="python -m kit.tooldocs", description=__doc__.split("\n\n")[0])
    sub = parser.add_subparsers(dest="action", required=True)
    p = sub.add_parser("check", help="check every page, the index and coverage; exit 1 on any problem")
    p.add_argument("--page", metavar="ID", help="check this one page only (no coverage or index check)")
    sub.add_parser("index", help="rewrite docs/tools/README.md's table and docs/tools/index.json")
    p = sub.add_parser("list", help="every tool, one line each")
    p.add_argument("--json", action="store_true", help="the index as JSON, as in docs/tools/index.json")
    p = sub.add_parser("show", help="print one tool's page")
    p.add_argument("id")
    p = sub.add_parser("new", help="start docs/tools/ID.md from templates/tool-doc.md")
    p.add_argument("id")
    p.add_argument("--kind", default="kit command", choices=KINDS)
    p.add_argument("--status", default="Current", choices=STATUSES)
    args = parser.parse_args(argv)

    if args.action == "check":
        problems = check_all(page_id=args.page)
        for line in problems:
            print(line)
        if problems:
            print(f"{len(problems)} problem(s); the standard is {STANDARD}", file=sys.stderr)
            return 1
        print(f"tool docs pass ({'page ' + args.page if args.page else str(len(load_pages())) + ' pages'})")
        return 0
    if args.action == "index":
        print(f"wrote docs/tools/README.md and docs/tools/index.json from {write_index()} pages")
        return 0
    pages = load_pages()
    if args.action == "list":
        if args.json:
            print(render_json(pages), end="")
        else:
            for p in sorted(pages, key=lambda p: p.id):
                run = p.spans("Run")
                print(f"{p.id:24} {p.field('Status'):13} {(run[0] if run else p.field('Run'))[:40]:40} {p.summary[:80]}")
        return 0
    if args.action == "show":
        page = next((p for p in pages if p.id == args.id), None)
        if page is None:
            near = difflib.get_close_matches(args.id, [p.id for p in pages], n=5, cutoff=0.4)
            print(f"no tool page {args.id!r}" + (f"; close: {', '.join(near)}" if near else ""), file=sys.stderr)
            return 2
        print(page.text, end="" if page.text.endswith("\n") else "\n")
        return 0
    try:
        path = new_page(args.id, args.kind, args.status)
    except ValueError as exc:
        print(exc, file=sys.stderr)
        return 2
    print(f"wrote {path.relative_to(ROOT).as_posix()}; fill it in, then run python -m kit.tooldocs check --page {args.id}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
